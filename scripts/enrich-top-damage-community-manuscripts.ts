function read(path: string) {
  return readFileSync(path, "utf8").replace(/\r\n?/g, "\n").trim();
}

function normalizeArticle(body: string) {
  let next = body.replace(/^# 미드 라인 실전 운용$/mu, "# 탑 라인 실전 운용");
  if (!next.includes("[[분류:탑]] [[분류:딜러]]")) {
    const lines = next.split("\n");
    const categoryLine = lines.findIndex((line) => line.startsWith("[[분류:"));
    if (categoryLine >= 0) {
      lines[categoryLine] = `${lines[categoryLine]} [[분류:탑]] [[분류:딜러]]`;
    } else {
      lines.splice(1, 0, "", "[[분류:탑]] [[분류:딜러]]");
    }
    next = lines.join("\n");
  }
  return next;
}

