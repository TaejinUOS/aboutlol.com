function detail(
  tempo: string,
  window: string,
  tracking: string,
  objective: string,
  teamfight: string,
  fallback: string,
  checks: Detail["checks"],
): Detail {
  return { tempo, window, tracking, objective, teamfight, fallback, checks };
}

function read(path: string) {
  return readFileSync(path, "utf8").replace(/\r\n?/g, "\n").trim();
}

function friendly(body: string) {
  return body
    .replace(/재사용 대기시간/gu, "스킬쿨")
    .replace(/기본 공격/gu, "평타")
    .replace(/궁극기/gu, "궁")
    .replace(/군중 제어/gu, "CC")
    .replace(/방해 효과/gu, "CC")
    .replace(/기술/gu, "스킬")
    .replace(/평타은/gu, "평타는")
    .replace(/평타을/gu, "평타를")
    .replace(/평타이/gu, "평타가")
    .replace(/평타으로/gu, "평타로")
    .replace(/궁는/gu, "궁은")
    .replace(/궁를/gu, "궁을")
    .replace(/궁가/gu, "궁이");
}

function enrich(body: string, extra: string) {
  const markerAt = body.indexOf(`\n${MARKER}`);
  const base = markerAt === -1 ? body : body.slice(0, markerAt).trimEnd();
  return `${base}\n\n${extra}`;
}

function addition(profile: Profile, value: Detail) {
  return `${MARKER}

## 초반 동선과 첫 개입
**무조건 정해진 동선을 외우기보다, 갱이 실패해도 다음 행동이 남는 쪽을 고른다.**[* [${profile.sourceLabel}](${profile.sourceUrl})] ${value.tempo}

## 맞딜과 핵심 스킬쿨
${value.window}

## 카정과 상대 정글 추적
${value.tracking}

## 용·전령 앞 판단
${value.objective}

## 한타에서 맡을 역할
${value.teamfight}

## 말렸을 때 복구법
${value.fallback}

## 게임 안에서 확인할 것
- ${value.checks.join("\n- ")}`;
}

function validate(profile: Profile, body: string, kind: "article" | "matchup") {
  const label = `${profile.name} ${kind === "article" ? "챔피언 위키" : "상대법"}`;
  assert(body.length >= 2_000, `${label}: 장문 기준 미달 (${body.length}자)`);
  assert(body.length <= MAX_BODY_LENGTH, `${label}: 본문 길이 초과`);
  assert(body.includes(profile.sourceUrl), `${label}: 커뮤니티 출처 누락`);
  assert(body.includes(MARKER), `${label}: 보강 문단 누락`);
  assert(/`[QWER]`/u.test(body), `${label}: 스킬 키 누락`);
  assert(!body.includes("기본 공격"), `${label}: 딱딱한 기본 공격 용어가 남아 있다`);
  assert(!body.includes("궁극기"), `${label}: 딱딱한 궁극기 용어가 남아 있다`);
  assert(!body.includes("재사용 대기시간"), `${label}: 딱딱한 쿨타임 용어가 남아 있다`);
  assert(!/(?:^|\s)(?:룬|아이템|소환사 주문)(?:\s|$)/mu.test(body), `${label}: 제외 주제 포함`);
  validateSourceFootnotes(body, label);
  if (kind === "article") {
    assert(body.includes("[[분류:정글]] [[분류:AD]]"), `${label}: 분류 누락`);
  }
  const outline = buildOutline(body, `${profile.slug}-${kind}`, 2, new Set());
  assert.equal(outline.children.length, 1);
  assert(outline.children[0].children.length >= 10, `${label}: 문단 수 부족`);
}
