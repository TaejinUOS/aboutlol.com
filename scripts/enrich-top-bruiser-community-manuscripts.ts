function validate(profile: Profile, body: string, kind: string) {
  const label = `${profile.name} ${kind}`;
  assert(body.length >= 2_000, `${label}: 장문 기준 미달 (${body.length}자)`);
  assert(body.length <= MAX_BODY_LENGTH, `${label}: 본문 길이 초과 (${body.length}자)`);
  assert(body.includes(profile.sourceUrl), `${label}: MOBAFire 출처 누락`);
  assert(body.includes(MARKER), `${label}: 보강 문단 누락`);
  assert(/`[QWER]`/u.test(body), `${label}: 스킬 키 누락`);
  assert(!/(?:^|\s)(?:룬|아이템|소환사 주문)(?:\s|$)/mu.test(body), `${label}: 제외 주제 포함`);
  validateSourceFootnotes(body, label);
  const outline = buildOutline(body, `${profile.slug}-${kind}`, 2, new Set());
  assert.equal(outline.children.length, 1);
  assert(outline.children[0].children.length >= 10, `${label}: 문단 수 부족`);
}
