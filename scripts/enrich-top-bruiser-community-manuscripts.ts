function detail(
  trade: string,
  cooldown: string,
  wave: string,
  macro: string,
  checks: readonly [string, string, string, string, string],
): Detail {
  return { trade, cooldown, wave, macro, checks };
}

function read(path: string) {
  return readFileSync(path, "utf8").replace(/\r\n?/g, "\n").trim();
}

function enrich(current: string, addition: string) {
  const markerAt = current.indexOf(`\n${MARKER}`);
  const base = markerAt === -1 ? current : current.slice(0, markerAt).trimEnd();
  return `${base}\n\n${addition}`;
}

