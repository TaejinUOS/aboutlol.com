**흐웨이의 세 파멸 기술은 같은 계열의 재사용 대기시간을 공유한다.** `QE`로 웨이브를 정리한 직후에는 `QQ`로 상대를 때릴 수 없으므로, 라인을 밀 목적과 체력을 깎을 목적을 한 번의 선택으로 구분한다. 상대가 막타를 치는 순간 두 목적이 겹칠 때만 함께 노린다.

## 고통 계열은 생존 자원으로 남긴다

**`EQ`의 공포, `EW`의 감시와 속박, `EE`의 끌어당김은 모두 같은 계열이다.** 돌진형 상대가 들어올 수 있는데 원거리 견제용으로 하나를 먼저 쓰면 나머지도 사용할 수 없다. 정면으로 달려오는 적에게는 `EQ`, 좁은 진입로나 수풀 확인에는 `EW`, 여러 대상의 경로를 모을 때는 `EE`처럼 상황을 먼저 정한다.

## `WE`는 안전한 막타와 함께 회수한다

**요동치는 빛은 다음 기본 공격이나 스킬에 추가 피해를 주고 적중 시 마나를 돌려준다.** 활성화만 하고 물러나면 마나 회복을 충분히 받지 못한다. 안전하게 칠 수 있는 미니언과 상대 위치를 확인한 뒤 사용해 세 번의 적중을 차분히 소비한다.

## 긴 사거리만 믿고 제어기를 함께 소모하지 않는다

**흐웨이는 멀리서 라인을 건드릴 수 있지만 이동기가 없다.** 파멸과 고통 기술을 한 번에 빗맞히면 상대가 들어오는 동안 막을 방법이 적다. 첫 제어가 빗나가면 추가 기술을 억지로 잇지 않고 거리를 다시 만든다.

